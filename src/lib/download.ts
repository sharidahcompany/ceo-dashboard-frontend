import { FileDownload } from "@/lib/utils";

// Server Actions can't stream a file straight to the browser, so exports/templates
// come back as base64; this turns that payload into an actual file-save prompt.
export function saveFileDownload({ base64, filename, contentType }: FileDownload) {
    const byteChars = atob(base64);
    const byteNumbers = new Array(byteChars.length);
    for (let i = 0; i < byteChars.length; i++) {
        byteNumbers[i] = byteChars.charCodeAt(i);
    }
    const blob = new Blob([new Uint8Array(byteNumbers)], { type: contentType });

    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    link.remove();
    URL.revokeObjectURL(url);
}
